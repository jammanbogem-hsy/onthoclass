function build(grid) {
  const rows = grid.trim().split("\n").map((r) => r.replace(/ /g, "."));
  let out = "";
  rows.forEach((row, y) => {
    let x = 0;
    while (x < row.length) {
      const ch = row[x];
      if (ch === "." || !C[ch]) { x++; continue; }
      let e = x; while (e + 1 < row.length && row[e + 1] === ch) e++;
      out += `<rect x="${x}" y="${y}" width="${e - x + 1}" height="1" fill="${C[ch]}"/>`;
      x = e + 1;
    }
  });
  return out;
}
const CACHE = {};
export const ICON_NAMES = Object.keys(G);
/** 픽셀 아이콘 svg 문자열. size 는 px(기본 1em). */
export function ic(name, size) {
  const body = CACHE[name] || (CACHE[name] = G[name] ? build(G[name]) : "");
  const s = size ? `width="${size}" height="${size}"` : `width="1em" height="1em"`;
  return `<svg class="pxi" viewBox="0 0 16 16" ${s} shape-rendering="crispEdges" aria-hidden="true" focusable="false">${body}</svg>`;
}
/** <i class="ic" data-i="이름" data-s="크기"> 를 아이콘으로 바꿔요. */
export function hydrateIcons(root = document) {
  root.querySelectorAll("i[data-i]:not([data-done])").forEach((el) => { el.innerHTML = ic(el.dataset.i, el.dataset.s); el.dataset.done = "1"; });
}
if (typeof document !== "undefined") {
  const go = () => hydrateIcons();
  if (document.readyState === "loading") document.addEventListener("DOMContentLoaded", go); else go();
  if (typeof MutationObserver !== "undefined") new MutationObserver(() => hydrateIcons()).observe(document.documentElement, { childList: true, subtree: true });
}
